def build_mock_events() -> list[dict]:
    today = datetime.now(UTC).date()
    events = []
    for i, (slug, title, cat, place, addr, min_age, desc, sessions) in enumerate(_RAW, 1):
        city = CITY_BY_SLUG[slug]
        tz = ZoneInfo(city.timezone)
        items = []
        for days, hhmm, capacity in sessions:
            h, m = map(int, hhmm.split(":"))
            d = today + timedelta(days=days)
            starts = datetime(d.year, d.month, d.day, h, m, tzinfo=tz)
            items.append((f"m{i}-{int(starts.timestamp())}", starts, capacity))
        events.append(
            {
                "id": f"m{i}",
                "title": title,
                "category": cat,
                "description": desc,
                "city": city,
                "place": place,
                "address": addr,
                "image": None,
                "min_age": min_age,
                "sessions": items,
                "source": "mock",
                "url": None,
            }
        )
    return events
